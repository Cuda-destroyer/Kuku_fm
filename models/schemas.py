"""
Structured exchange schemas for LLM prompts, parser manifests, and reports.
"""
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from models.episode import Episode, CharacterProfile, StoryEvent
from models.promo import HookCandidate, CliffhangerCandidate, PromoCandidate, PromoSegment, ScoreBreakdown, ValidationResult


class EpisodeManifestItem(BaseModel):
    """Manifest summary entry for an ingested episode."""
    episode_id: str
    filename: str
    parsing_status: str
    scene_count: int
    dialogue_count: int
    character_count: int
    total_duration_str: str
    timestamp_coverage: str
    warnings: List[str] = Field(default_factory=list)


class LLMEpisodeAnalysis(BaseModel):
    """Output schema for episode story analysis."""
    episode_id: str
    main_conflict: str
    characters: List[CharacterProfile] = Field(default_factory=list)
    key_events: List[StoryEvent] = Field(default_factory=list)
    revelations_and_betrayals: List[str] = Field(default_factory=list)
    emotional_arc: str
    potential_promotional_themes: List[str] = Field(default_factory=list)


class LLMHookItem(BaseModel):
    """Structured hook item from LLM."""
    timestamp: str
    character_or_element: str
    quote_or_action: str
    hook_type: str
    scroll_stop_reason: str
    score: float = Field(..., ge=0, le=100)
    confidence: float = Field(0.9, ge=0, le=1.0)


class LLMCliffhangerItem(BaseModel):
    """Structured cliffhanger item from LLM."""
    timestamp: str
    event_description: str
    unresolved_question: str
    viewer_anticipation_reason: str
    score: float = Field(..., ge=0, le=100)
    confidence: float = Field(0.9, ge=0, le=1.0)


class LLMContextEvaluation(BaseModel):
    """Structured context evaluation from LLM."""
    context_rating: str = Field(..., description="Excellent, Good, Weak, or Poor")
    character_clarity: str
    conflict_clarity: str
    prior_knowledge_needed: bool
    explanation: str
    context_score: float = Field(..., ge=0, le=100)


class LLMPromoCandidateRaw(BaseModel):
    """Raw structured candidate generated by LLM prior to deterministic Python validation."""
    title: str
    segment_type: str = "continuous"  # continuous or multi_segment
    segments: List[Dict[str, Any]]
    hook_timestamp: str
    hook_description: str
    hook_score: float
    cliffhanger_timestamp: str
    cliffhanger_description: str
    cliffhanger_score: float
    narrative_coherence_explanation: str
    standalone_context_rating: str
    coherence_score: float
    emotional_intensity_score: float
    curiosity_score: float
