"""
High-fidelity Mock / Heuristic LLM Provider for offline testing, UI verification, and unit tests.
Explicitly labels all generated candidates as [HEURISTIC / MOCK MODE].
"""
import re
from typing import Dict, Any, List, Optional, Type, TypeVar, Tuple
from pydantic import BaseModel

from llm.base_provider import BaseLLMProvider
from models.episode import Episode, CharacterProfile, StoryEvent
from models.promo import HookCandidate, CliffhangerCandidate, PromoCandidate
from models.schemas import (
    LLMEpisodeAnalysis,
    LLMContextEvaluation,
    LLMPromoCandidateRaw,
)

T = TypeVar("T", bound=BaseModel)


class MockProvider(BaseLLMProvider):
    """Offline heuristic provider for testing without Hugging Face API access."""

    def __init__(self, model_id: str = "mock-heuristic-v1"):
        self._model_id = model_id

    @property
    def provider_name(self) -> str:
        return "mock"

    @property
    def model_id(self) -> str:
        return self._model_id

    def health_check(self) -> Tuple[bool, str]:
        return True, "Mock / Heuristic provider is operational (Offline Mode)."

    def generate_text(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        max_tokens: int = 1000,
        temperature: float = 0.3,
    ) -> str:
        return '{"status": "mock_response", "note": "Generated by MockProvider for offline testing"}'

    def generate_structured(
        self,
        prompt: str,
        response_schema: Type[T],
        system_prompt: Optional[str] = None,
        max_tokens: int = 1500,
        temperature: float = 0.2,
    ) -> T:
        raise NotImplementedError("Generic generate_structured not supported in MockProvider; use domain methods.")

    def analyze_episode(self, episode: Episode) -> LLMEpisodeAnalysis:
        characters = []
        for cname in episode.characters[:4]:
            role = "protagonist" if "JULIANA" in cname.upper() else ("antagonist" if "GERALD" in cname.upper() or "GOLD" in cname.upper() or "MATRIARCH" in cname.upper() else "supporting")
            characters.append(
                CharacterProfile(
                    name=cname,
                    role=role,
                    description=f"Key character appearing in {episode.episode_id}",
                    relationships={"rival": "Conflict over family status and betrayal"}
                )
            )

        events = []
        for i, sc in enumerate(episode.scenes):
            for el in sc.elements:
                if el.element_type == "DIALOGUE" and any(w in el.text.lower() for w in ["never", "marry", "betray", "father", "leave", "shame", "kill", "die", "oath"]):
                    events.append(
                        StoryEvent(
                            event_id=f"EV-{episode.episode_id}-{len(events)+1:02d}",
                            episode_id=episode.episode_id,
                            timestamp_str=el.start_str,
                            start_seconds=el.start_seconds,
                            end_seconds=el.end_seconds,
                            description=f"{el.speaker or 'Character'} states: {el.text[:80]}",
                            event_type="conflict",
                            intensity_score=85.0,
                            characters_involved=[el.speaker] if el.speaker else []
                        )
                    )
                    if len(events) >= 3:
                        break
            if len(events) >= 3:
                break

        return LLMEpisodeAnalysis(
            episode_id=episode.episode_id,
            main_conflict=f"Intense confrontation involving {', '.join(episode.characters[:3])} in {episode.episode_id}.",
            characters=characters,
            key_events=events,
            revelations_and_betrayals=[f"Dramatic confrontation in {episode.episode_id}"],
            emotional_arc="High tension and public humiliation escalating to emotional defiance.",
            potential_promotional_themes=["Betrayal at the altar", "Public shaming", "Underdog resilience"]
        )

    def extract_characters(self, episode: Episode) -> List[CharacterProfile]:
        profiles = []
        for name in episode.characters:
            role = "protagonist" if "JULIANA" in name.upper() else ("antagonist" if "GERALD" in name.upper() or "GOLD" in name.upper() else "supporting")
            profiles.append(
                CharacterProfile(
                    name=name,
                    role=role,
                    description=f"Character appearing in {episode.episode_id}",
                    relationships={}
                )
            )
        return profiles

    def detect_hooks(self, episode: Episode) -> List[HookCandidate]:
        """Discovers hooks by scanning dialogue and actions within the first 60 seconds."""
        hooks = []
        hook_count = 0

        # Keywords signalling high-impact hooks
        shock_keywords = [
            "turn around", "not anymore", "look for yourself", "marrying me", "changed my mind",
            "never", "stop", "liar", "betray", "shame", "who is", "what do you mean", "slap", "kneel"
        ]

        for sc in episode.scenes:
            for el in sc.elements:
                if el.start_seconds <= 75.0:  # Hooks should appear near beginning
                    text_lower = el.text.lower()
                    is_hit = any(kw in text_lower for kw in shock_keywords)
                    if is_hit or (el.element_type == "DIALOGUE" and ("!" in el.text or "?" in el.text)):
                        hook_count += 1
                        speaker_label = f"{el.speaker}: " if el.speaker else ""
                        hooks.append(
                            HookCandidate(
                                hook_id=f"HOOK-{episode.episode_id}-{hook_count:02d}",
                                episode_id=episode.episode_id,
                                source_timestamp=el.start_str,
                                start_seconds=el.start_seconds,
                                end_seconds=el.end_seconds,
                                relevant_content=f"{speaker_label}\"{el.text}\"",
                                hook_type="shocking_statement" if el.element_type == "DIALOGUE" else "dramatic_action",
                                explanation=f"[HEURISTIC / MOCK MODE] High-impact opening line/action halting user scroll.",
                                hook_score=88.0 if is_hit else 78.0,
                                confidence=0.85,
                                screenplay_reference=f"[{el.start_str}] {speaker_label}{el.text}"
                            )
                        )
                if len(hooks) >= 4:
                    break
            if len(hooks) >= 4:
                break

        return hooks

    def detect_cliffhangers(self, episode: Episode) -> List[CliffhangerCandidate]:
        """Discovers cliffhangers near scene endings or final episode beats."""
        cliffhangers = []
        cliff_count = 0

        for sc in episode.scenes:
            # Look at elements near the end of scene
            elements = sc.elements[-10:] if len(sc.elements) >= 10 else sc.elements
            for el in reversed(elements):
                text_lower = el.text.lower()
                is_unresolved = (
                    "cut to black" in text_lower
                    or "cliffhanger" in text_lower
                    or "?" in el.text
                    or any(w in text_lower for w in ["defiance", "fury", "refusing", "stares", "silence", "swear", "never"])
                )
                if is_unresolved or el.element_type in ("ACTION", "SOUND FX"):
                    cliff_count += 1
                    speaker_label = f"{el.speaker}: " if el.speaker else ""
                    cliffhangers.append(
                        CliffhangerCandidate(
                            cliffhanger_id=f"CLIFF-{episode.episode_id}-{cliff_count:02d}",
                            episode_id=episode.episode_id,
                            source_timestamp=el.start_str,
                            start_seconds=el.start_seconds,
                            end_seconds=el.end_seconds,
                            event_description=f"{speaker_label}{el.text}",
                            unresolved_element=f"[HEURISTIC / MOCK MODE] Climax cut leaving the confrontation unresolved.",
                            why_viewer_continues="Viewer needs to know how the humiliated protagonist responds.",
                            cliffhanger_score=87.0 if is_unresolved else 75.0,
                            confidence=0.85,
                            screenplay_reference=f"[{el.start_str}] {speaker_label}{el.text}"
                        )
                    )
                if len(cliffhangers) >= 3:
                    break

        return cliffhangers

    def evaluate_context(
        self, promo_title: str, segment_type: str, segments_summary: str, dialogue_summary: str
    ) -> LLMContextEvaluation:
        # Heuristic: if dialogue contains clear character names and accusations, context is Good/Excellent
        has_conflict = any(w in dialogue_summary.lower() for w in ["marry", "betray", "sister", "gerald", "father", "shame"])
        rating = "Excellent" if has_conflict else "Good"
        return LLMContextEvaluation(
            context_rating=rating,
            character_clarity="Characters have distinct opposing motivations evident from the dialogue.",
            conflict_clarity="Public rejection and family conspiracy are immediately obvious to a new viewer.",
            prior_knowledge_needed=False,
            explanation="[HEURISTIC / MOCK MODE] The core conflict of betrayal at the altar requires zero previous lore.",
            context_score=90.0 if rating == "Excellent" else 80.0
        )

    def generate_candidates(
        self, episode: Episode, show_context: Optional[str] = None
    ) -> List[LLMPromoCandidateRaw]:
        """Generates candidate definitions adhering to 20-60 second window."""
        candidates = []

        # Find best hook and cliffhanger
        hooks = self.detect_hooks(episode)
        cliffhangers = self.detect_cliffhangers(episode)

        if not hooks or not cliffhangers:
            return []

        # 1. Continuous Promo Candidate (e.g. 30-45s span)
        for h in hooks[:2]:
            for c in cliffhangers[:2]:
                duration = c.end_seconds - h.start_seconds
                if 20.0 <= duration <= 60.0:
                    candidates.append(
                        LLMPromoCandidateRaw(
                            title=f"The Altar Betrayal ({episode.episode_id}) [Heuristic]",
                            segment_type="continuous",
                            segments=[{
                                "segment_order": 1,
                                "episode_id": episode.episode_id,
                                "start_timestamp": h.source_timestamp,
                                "end_timestamp": c.source_timestamp,
                                "start_seconds": h.start_seconds,
                                "end_seconds": c.end_seconds,
                                "selected_moment": "Full escalating altar confrontation sequence",
                                "reason_for_inclusion": "Continuous dramatic escalation from initial shock to cold cliffhanger",
                            }],
                            hook_timestamp=h.source_timestamp,
                            hook_description=h.relevant_content,
                            hook_score=h.hook_score,
                            cliffhanger_timestamp=c.source_timestamp,
                            cliffhanger_description=c.event_description,
                            cliffhanger_score=c.cliffhanger_score,
                            narrative_coherence_explanation="Uninterrupted sequence capturing the revelation, public shaming, and resolute defiance.",
                            standalone_context_rating="Excellent",
                            coherence_score=92.0,
                            emotional_intensity_score=90.0,
                            curiosity_score=88.0,
                        )
                    )
                    break
            if candidates:
                break

        # 2. Multi-segment candidate if available
        if len(episode.scenes) > 0 and hooks and cliffhangers:
            h = hooks[0]
            c = cliffhangers[0]
            seg1_end = min(h.start_seconds + 16.0, episode.total_duration_seconds)
            seg2_start = max(seg1_end + 5.0, c.start_seconds - 15.0)
            seg2_end = min(seg2_start + 18.0, c.end_seconds)

            dur = (seg1_end - h.start_seconds) + (seg2_end - seg2_start)
            if 20.0 <= dur <= 60.0 and seg2_start > seg1_end:
                from core.timestamp_utils import format_seconds
                candidates.append(
                    LLMPromoCandidateRaw(
                        title=f"Shattered Vows ({episode.episode_id}) [Montage Cut]",
                        segment_type="multi_segment",
                        segments=[
                            {
                                "segment_order": 1,
                                "episode_id": episode.episode_id,
                                "start_timestamp": h.source_timestamp,
                                "end_timestamp": format_seconds(seg1_end),
                                "start_seconds": h.start_seconds,
                                "end_seconds": seg1_end,
                                "selected_moment": "Initial shock and cruel revelation",
                                "reason_for_inclusion": "High-impact opening hook establishing the betrayal",
                            },
                            {
                                "segment_order": 2,
                                "episode_id": episode.episode_id,
                                "start_timestamp": format_seconds(seg2_start),
                                "end_timestamp": format_seconds(seg2_end),
                                "start_seconds": seg2_start,
                                "end_seconds": seg2_end,
                                "selected_moment": "Father's cold abandonment and final cliffhanger look",
                                "reason_for_inclusion": "Escalating family betrayal culminating in unresolved tension",
                            }
                        ],
                        hook_timestamp=h.source_timestamp,
                        hook_description=h.relevant_content,
                        hook_score=h.hook_score,
                        cliffhanger_timestamp=format_seconds(seg2_end),
                        cliffhanger_description=c.event_description,
                        cliffhanger_score=c.cliffhanger_score,
                        narrative_coherence_explanation="Combines the immediate altar confrontation with the father's rejection for maximum emotional impact.",
                        standalone_context_rating="Good",
                        coherence_score=86.0,
                        emotional_intensity_score=92.0,
                        curiosity_score=90.0,
                    )
                )

        return candidates

    def evaluate_promo(self, candidate: PromoCandidate) -> Dict[str, Any]:
        return {
            "marketing_angle": "Emotional betrayal & noble revenge melodrama",
            "target_audience": "Female 18-45, Romance/Drama mobile video consumers",
            "viral_conversion_potential": "High",
            "editorial_recommendation": "Recommend strongly",
            "final_editorial_notes": "[HEURISTIC / MOCK MODE] Strong emotional hook with immediate villain clarity."
        }
